    def create(self, vals_list):
        for vals in vals_list:
            if not vals.get("name") or vals.get("name") in ("/", False):
                vals["name"] = self.env["ir.sequence"].sudo().next_by_code("clinic.billing.payment") or "/"
        recs = super().create(vals_list)
        for rec in recs:
            rec._on_after_create()
        return recs

    def _on_after_create(self):
        """Hook: schedule activities, audit log, etc."""
        pass

    def write(self, vals):
        res = super().write(vals)
        return res


