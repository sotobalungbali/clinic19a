    # ---------------------------------------------------------------------
    # Computes
    # ---------------------------------------------------------------------
    @api.depends("amount", "fee_amount")
    def _compute_net(self):
        for rec in self:
            amt = rec.amount or 0.0
            fee = rec.fee_amount or 0.0
            rec.net_amount = max(amt - fee, 0.0)

    # ---------------------------------------------------------------------
    # Validations
    # ---------------------------------------------------------------------
    @api.constrains("amount")
    def _check_amount_positive(self):
        for rec in self:
            if rec.amount <= 0:
                raise ValidationError(_("Payment line amount must be positive."))

    # ---------------------------------------------------------------------
    # Soft dependency access
    # ---------------------------------------------------------------------
    @api.model
    def _model(self, model_name):
        return self.env[model_name] if model_name in self.env else False

    # ---------------------------------------------------------------------
    # Core creation of account.payment
    # ---------------------------------------------------------------------
    def _create_account_payment(self):
        """
        Create & post an account.payment for this line when applicable.
        - For membership/insurance/voucher: either create payment in a designated journal
          (if configured), or rely on hooks to settle wallet/claim without account.payment.
        """
        self.ensure_one()

        # If already created, return it
        if self.account_payment_id:
            if self.account_payment_id.state == "draft":
                self.account_payment_id.sudo().action_post()
            elif self.account_payment_id.state in ("canceled", "rejected"):
                raise UserError(_("The linked accounting payment is cancelled/rejected and cannot be reused."))
            return self.account_payment_id

        # Decide if we should create an account.payment for this method
        create_ap = self._should_create_account_payment()
        ap = False

        if create_ap:
            journal = self._resolve_journal()
            if not journal:
                raise UserError(_("Please set a Journal on the payment line (method: %s).") % (self.method,))

            vals = {
                "payment_type": "inbound",      # customer payment
                "partner_type": "customer",
                "partner_id": self.partner_id.id,
                "amount": self.amount,
                "currency_id": self.currency_id.id,
                "date": self.payment_id.date,
                "memo": self._build_payment_ref(),
                "payment_reference": self.reference or self._build_payment_ref(),
                "journal_id": journal.id,
                "company_id": self.company_id.id,
                "clinic_invoice_id": self.invoice_id.id,
                "clinic_payment_id": self.payment_id.id,
                "clinic_note": self.note or self.reference or self.payment_id.narration,
            }
            ap = self.env["account.payment"].sudo().create(vals)
            # Post it
            ap.sudo().action_post()
            self.account_payment_id = ap.id

        # Hooks for side-effects regardless of account.payment creation
        self._hook_gateway_capture()
        self._hook_membership_debit()
        self._hook_insurance_settlement()
        self._hook_audit_log("create_line_payment", {"line_id": self.id, "ap_id": ap.id if ap else False})

        return ap

    # ---------------------------------------------------------------------
    # Decisions & Resolutions
    # ---------------------------------------------------------------------
    def _should_create_account_payment(self):
        """
        Decide whether to create account.payment for this method.
        Default: True for cash/bank/card/ewallet/transfer/other; False for voucher.
        Membership/Insurance: True if journal is set; else False (handled by hooks).
        """
        if self.method in ("cash", "bank_transfer", "card", "ewallet", "other"):
            return True
        if self.method == "voucher":
            return False
        if self.method in ("membership", "insurance"):
            # If journal is provided, we'll create an accounting entry; otherwise rely on the specific module.
            return bool(self.journal_id)
        return True

    def _resolve_journal(self):
        """Prefer line.journal_id; otherwise try company default inbound payment journal."""
        if self.journal_id:
            return self.journal_id
        # fallback: any bank/cash/general journal for inbound
        Journal = self.env["account.journal"].sudo()
        journal = Journal.search([
            ("type", "in", ("bank", "cash", "general")),
            ("company_id", "=", self.company_id.id)
        ], limit=1)
        return journal

    def _build_payment_ref(self):
        ref = "[%s] %s" % (self.method.upper(), self.payment_id.name or "")
        if self.reference:
            ref = "%s - %s" % (ref, self.reference)
        if self.gateway_provider and self.gateway_provider != "none":
            ref = "%s (%s:%s)" % (ref, self.gateway_provider, self.gateway_tx_id or "-")
        return ref

