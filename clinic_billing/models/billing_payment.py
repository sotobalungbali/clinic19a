    amount_net = fields.Monetary(
        string="Net To Reconcile",
        compute="_compute_amounts",
        store=False,
        help="Total - fees (informational; accounting uses line setup)."
    )

    payments_generated_ids = fields.Many2many(
        "account.payment",
        "clinic_payment_to_account_payment_rel",
        "clinic_payment_id",
        "account_payment_id",
        string="Generated Account Payments",
        readonly=True,
        help="Account payments generated by this clinic payment."
    )

    # ---------------------------------------------------------------------
    # Registry helper for soft deps
    # ---------------------------------------------------------------------
    @api.model
    def _model(self, model_name):
        return self.env[model_name] if model_name in self.env else False

    # ---------------------------------------------------------------------
    # Computes
    # ---------------------------------------------------------------------
    @api.depends("line_ids.amount", "line_ids.fee_amount")
    def _compute_amounts(self):
        for rec in self:
            total = sum(l.amount for l in rec.line_ids)
            fee = sum(l.fee_amount for l in rec.line_ids)
            rec.amount_total = total
            rec.amount_fee = fee
            rec.amount_net = (total - fee) if rec.currency_id else total

    # ---------------------------------------------------------------------
    # Constraints
    # ---------------------------------------------------------------------
    @api.constrains("invoice_id")
    def _check_invoice_required(self):
        for rec in self:
            if not rec.invoice_id:
                raise ValidationError(_("Clinic Invoice is required."))

    @api.constrains("line_ids")
    def _check_lines(self):
        for rec in self:
            if not rec.line_ids:
                raise ValidationError(_("Please add at least one payment line."))
            for l in rec.line_ids:
                if l.amount <= 0:
                    raise ValidationError(_("Payment line amount must be positive."))

    # ---------------------------------------------------------------------
    # Sequence
    # ---------------------------------------------------------------------
    def _next_sequence(self):
        return self.env["ir.sequence"].sudo().next_by_code("clinic.billing.payment") or "/"

    # ---------------------------------------------------------------------
    # Lifecycle
    # ---------------------------------------------------------------------
    def action_confirm(self):
        """Validate basic data and switch to Confirmed."""
        for rec in self:
            if rec.state != "draft":
                continue
            if rec.name in ("/", False, ""):
                rec.name = rec._next_sequence()
            # Extra validations vs invoice residual (informational)
            if rec.move_id:
                residual = rec.move_id.amount_residual
                pay_total = rec.amount_total
                if pay_total > residual and not rec.allow_overpayment:
                    raise UserError(_(
                        "Payment amount (%.2f) exceeds invoice residual (%.2f). "
                        "Enable 'Allow Overpayment' or adjust lines."
                    ) % (pay_total, residual))
                if pay_total < residual and not rec.allow_underpayment:
                    # Not blocking; let them proceed if desired by enabling flag
                    raise UserError(_(
                        "Payment amount (%.2f) is less than invoice residual (%.2f). "
                        "Enable 'Allow Underpayment' to proceed or adjust lines."
                    ) % (pay_total, residual))
            # Hooks
            rec._on_after_confirm()
            rec.state = "confirmed"
        return True

    def _on_after_confirm(self):
        """Hook for gateway pre-authorization, membership reserving, etc."""
        # e.g., call gateway to pre-auth hold if line.method == 'card' with capture later.
        pass

    def action_post(self):
        """
        Create & post account.payment for each line (where applicable),
        then reconcile with invoice. Switch to Posted/Reconciled accordingly.
        """
        for rec in self:
            if rec.state not in ("confirmed", "draft"):
                continue
            if not rec.move_id:
                raise UserError(_("No accounting invoice linked on the clinic invoice."))

            generated_payments = []
            for line in rec.line_ids:
                ap = line._create_account_payment()
                if ap:
                    generated_payments.append(ap.id)

            if generated_payments:
                rec.payments_generated_ids = [(6, 0, generated_payments)]
            # Try to reconcile
            rec._reconcile_to_invoice()

            # Update state based on accounting
            rec.state = "reconciled" if rec.invoice_id.is_paid else "posted"

            # Hooks after posting (commission, audit, membership/insurance finalize)
            rec._on_after_post()
        return True

    def _on_after_post(self):
        """Hook: audit trails, notify, finalize insurance/membership settlements."""
        # Example:
        # if self._model("clinic.audit.log"):
        #     self.env["clinic.audit.log"].sudo().create({ ... })
        pass

    def action_cancel(self):
        """
        Cancel only when no posted account.payments exist or invoice not posted.
        For robust flows, prefer refund rather than cancel after posting.
        """
        for rec in self:
            if rec.state in ("reconciled", "posted"):
                raise UserError(_("Cannot cancel a posted/reconciled payment. Please refund instead."))
            rec._on_before_cancel()
            rec.state = "cancelled"
            rec._on_after_cancel()
        return True

    def _on_before_cancel(self):
        """Hook: rollback gateway pre-auth or membership reservations."""
        pass

    def _on_after_cancel(self):
        """Hook: audit logging on cancellation."""
        pass

    # ---------------------------------------------------------------------
    # Reconciliation
    # ---------------------------------------------------------------------
    def _reconcile_to_invoice(self):
        """
        Reconcile generated payments to the accounting invoice using Odoo APIs.
        Safe against version changes by trying standard flows first.
        """
        for rec in self:
            move = rec.move_id
            if not move or move.state != "posted":
                # Post the invoice first if needed
                if move and move.state != "posted":
                    move.sudo().action_post()

            # Collect posted payment moves from generated account.payments
            payments = rec.payments_generated_ids.filtered(lambda p: p.state in ("in_process", "paid"))
            if not payments:
                continue

            # Attempt to use js_assign_outstanding_line if available (typical)
            for payment in payments:
                # Find the receivable line on the payment move
                pay_receivable_lines = payment.move_id.line_ids.filtered(
                    lambda l: l.account_id.account_type == "asset_receivable"
                    and l.balance < 0  # credit on receivable for inbound payment
                )
                # Fallback: any receivable line on the payment move.
                if not pay_receivable_lines:
                    pay_receivable_lines = payment.move_id.line_ids.filtered(
                        lambda line: line.account_id.account_type == "asset_receivable"
                        and not line.reconciled
                    )
                if not pay_receivable_lines:
                    raise UserError(_(
                        "Accounting payment %s has no open receivable line to reconcile."
                    ) % payment.display_name)

                for payment_line in pay_receivable_lines:
                    if move.payment_state == "paid":
                        break
                    try:
                        # Standard Odoo invoice helper for assigning an outstanding payment.
                        move.js_assign_outstanding_line(payment_line.id)
                    except Exception as primary_error:
                        # Deterministic fallback: reconcile open receivable lines directly.
                        invoice_receivable = move.line_ids.filtered(
                            lambda line: line.account_id.account_type == "asset_receivable"
                            and not line.reconciled
                        )
                        compatible_invoice_lines = invoice_receivable.filtered(
                            lambda line: line.account_id == payment_line.account_id
                        )
                        if not compatible_invoice_lines:
                            raise UserError(_(
                                "Payment %s cannot be reconciled to invoice %s because "
                                "their receivable accounts do not match."
                            ) % (payment.display_name, move.display_name)) from primary_error
                        try:
                            (compatible_invoice_lines | payment_line).reconcile()
                        except Exception as fallback_error:
                            raise UserError(_(
                                "Failed to reconcile accounting payment %s to invoice %s. "
                                "No ClinicOne payment state was finalized.\n\n%s"
                            ) % (
                                payment.display_name,
                                move.display_name,
                                fallback_error,
                            )) from fallback_error

            # Sync clinic invoice state with account.move
            rec.invoice_id._sync_state_from_move()

    # ---------------------------------------------------------------------
    # Smart buttons / UI actions
    # ---------------------------------------------------------------------
    def action_view_account_payments(self):
        self.ensure_one()
        action = self.env.ref("account.action_account_payments").read()[0]
        action.update({
            "domain": [("id", "in", self.payments_generated_ids.ids)],
            "context": {"search_default_customer": 1},
        })
        return action

    def unlink(self):
        locked = self.filtered(lambda rec: rec.state not in ("draft", "cancelled", "failed"))
        if locked:
            raise UserError(_("Only Draft, Cancelled, or Failed clinic payments can be deleted."))
        return super().unlink()

    # ---------------------------------------------------------------------
    # CRUD
    # ---------------------------------------------------------------------
