    # =====================================================================
    # COMPUTES
    # =====================================================================
    @api.depends("code", "name", "specialty")
    def _compute_display_name(self):
        for rec in self:
            parts = []
            if rec.code and rec.code != "/":
                parts.append(f"[{rec.code}]")
            if rec.name:
                parts.append(rec.name)
            if rec.specialty:
                parts.append(f"• {rec.specialty}")
            rec.display_name = " ".join(parts) if parts else _("Practitioner")

    @api.depends("staff_id")
    def _compute_employee_partner_role(self):
        Staff = self.env["clinic.staff"]
        has_employee = "employee_id" in Staff._fields
        has_partner = "partner_id" in Staff._fields
        has_role = "role" in Staff._fields
        for rec in self:
            rec.employee_id = rec.staff_id.employee_id if has_employee else False
            rec.partner_id = rec.staff_id.partner_id if has_partner else False
            rec.role = rec.staff_id.role if has_role else "other"

    @api.depends("staff_id")
    def _compute_compliance(self):
        """Aggregate compliance from clinic.staff.license (if available)."""
        License = self.env.get("clinic.staff.license")
        today = fields.Date.context_today(self)
        for rec in self:
            latest = False
            compliant = True  # default: lenient when license module not installed
            if License and rec.staff_id:
                # consider active licenses, not expired
                ls = License.search([
                    ("staff_id", "=", rec.staff_id.id),
                    ("state", "in", ["active", "valid", "approved"]),
                ])
                # if license module exists but no active licenses, mark not compliant
                compliant = False
                for l in ls:
                    # guard expiry field names
                    exp = False
                    if "valid_to" in l._fields:
                        exp = l.valid_to
                    elif "expiration_date" in l._fields:
                        exp = l.expiration_date
                    elif "date_to" in l._fields:
                        exp = l.date_to
                    # evaluate compliance per license
                    if not exp or exp >= today:
                        compliant = True
                        if not latest or (exp and latest and exp > latest) or (exp and not latest):
                            latest = exp
                rec.license_valid_until = latest or False
            else:
                rec.license_valid_until = False
            rec.is_license_compliant = bool(compliant)

    @api.depends("active", "is_license_compliant", "staff_id")
    def _compute_readiness(self):
        """Ready if active + license compliant + (optional) presence/availability signal."""
        Presence = self.env.get("clinic.staff.presence")
        Availability = self.env.get("clinic.staff.availability")
        Roster = self.env.get("clinic.staff.roster")
        now = fields.Datetime.now()
        for rec in self:
            ready = bool(rec.active and rec.is_license_compliant)
            nxt = False
            # If presence model exists, check current presence
            if ready and Presence and rec.staff_id:
                pr = Presence.search([("staff_id", "=", rec.staff_id.id)], limit=1, order="check_in desc")
                if pr and "state" in pr._fields:
                    # Treat 'present' / 'on_shift' as available hint
                    state = pr.state or "absent"
                    if state not in ("present", "on_shift", "available"):
                        ready = False
            # Provide a soft "next available" hint from availability/roster
            if Availability and rec.staff_id:
                slot = Availability.search([
                    ("staff_id", "=", rec.staff_id.id),
                    ("end", ">", now),
                ], limit=1, order="start asc")
                nxt = slot.start if slot and "start" in slot._fields else False
            elif Roster and rec.staff_id:
                line = Roster.search([
                    ("staff_id", "=", rec.staff_id.id),
                    ("date_end", ">", now),
                ], limit=1, order="date_start asc")
                if line and "date_start" in line._fields:
                    nxt = line.date_start
            rec.is_ready_for_assignment = ready
            rec.next_available_from = nxt

    def _compute_counts(self):
        Assignment = self.env.get("clinic.staff.assignment")
        Availability = self.env.get("clinic.staff.availability")
        License = self.env.get("clinic.staff.license")
        Roster = self.env.get("clinic.staff.roster")

        for rec in self:
            sid = rec.staff_id.id
            rec.assignment_count = Assignment.search_count([("staff_id", "=", sid)]) if Assignment and sid else 0
            rec.availability_count = Availability.search_count([("staff_id", "=", sid)]) if Availability and sid else 0
            rec.license_count = License.search_count([("staff_id", "=", sid)]) if License and sid else 0
            rec.roster_count = Roster.search_count([("staff_id", "=", sid)]) if Roster and sid else 0

    # =====================================================================
    # CREATE / WRITE
    # =====================================================================
    @api.model_create_multi
    def create(self, vals_list):
        seq = self.env["ir.sequence"]
        for vals in vals_list:
            # Generate code if missing
            if not vals.get("code") or vals.get("code") in ("/",):
                vals["code"] = seq.next_by_code("clinic.practitioner") or "/"
            # Default name from staff if not provided
            if not vals.get("name") and vals.get("staff_id"):
                staff = self.env["clinic.staff"].browse(vals["staff_id"])
                vals["name"] = staff.display_name or staff.name or _("Practitioner")
            # Company & branch defaults
            vals.setdefault("company_id", self.env.company.id)
            if vals.get("staff_id") and "branch_id" not in vals:
                Staff = self.env["clinic.staff"].browse(vals["staff_id"])
                if "branch_id" in Staff._fields and Staff.branch_id:
                    vals["branch_id"] = Staff.branch_id.id
        recs = super().create(vals_list)
        return recs

    def write(self, vals):
        # Keep name synchronized if staff changes and name wasn't manually edited
        if "staff_id" in vals and "name" not in vals:
            new_staff = self.env["clinic.staff"].browse(vals.get("staff_id"))
            vals["name"] = new_staff.display_name or new_staff.name
        return super().write(vals)

    # =====================================================================
    # CONSTRAINTS
    # =====================================================================
    @api.constrains("staff_id", "role")
    def _check_staff_role_practitioner(self):
        """Optional guard: only allow practitioner roles."""
        Staff = self.env["clinic.staff"]
        has_role = "role" in Staff._fields
        for rec in self:
            if not rec.staff_id:
                raise ValidationError(_("A practitioner must be linked to a staff."))
            if has_role:
                role = rec.staff_id.role or rec.role
                if role not in ("doctor", "nurse", "therapist", "other"):
                    raise ValidationError(_("Linked staff role is not allowed as practitioner."))

    # =====================================================================
    # NAME GET / SEARCH
    # =====================================================================
    def name_get(self):
        res = []
        for rec in self:
            name = rec.display_name or rec.name or rec.code or _("Practitioner")
            res.append((rec.id, name))
        return res

    @api.model
    def name_search(self, name="", domain=None, operator="ilike", limit=100):
        domain = domain or []
        name_domain = ["|", ("code", operator, name), ("name", operator, name)]
        recs = self.search(name_domain + domain, limit=limit)
        return [(rec.id, rec.display_name) for rec in recs.sudo()]

