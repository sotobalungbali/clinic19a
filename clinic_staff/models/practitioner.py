    def ensure_license_compliant(self, at_date=None):
        """Raise if license not compliant at given date (default today)."""
        at = at_date or fields.Date.context_today(self)
        for rec in self:
            # If license module absent, allow by design (soft integration).
            if self.env.get("clinic.staff.license"):
                if not rec.is_license_compliant:
                    raise ValidationError(_("Practitioner is not license-compliant."))
                if rec.license_valid_until and rec.license_valid_until < at:
                    raise ValidationError(_("Practitioner's license is expired."))

    def is_available_at(self, at_dt=None):
        """Soft check: available if marked ready and (optionally) coverage exists in availability/roster."""
        at = at_dt or fields.Datetime.now()
        for rec in self:
            if not rec.is_ready_for_assignment:
                return False
            Availability = self.env.get("clinic.staff.availability")
            Roster = self.env.get("clinic.staff.roster")
            if Availability:
                ok = Availability.search_count([
                    ("staff_id", "=", rec.staff_id.id),
                    ("start", "<=", at),
                    ("end", ">=", at),
                ]) > 0
                if ok:
                    return True
            if Roster:
                ok = Roster.search_count([
                    ("staff_id", "=", rec.staff_id.id),
                    ("date_start", "<=", at),
                    ("date_end", ">=", at),
                ]) > 0
                if ok:
                    return True
            # If no availability/roster modules, fall back to readiness
            return True

