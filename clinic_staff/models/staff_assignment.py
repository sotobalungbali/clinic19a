    @api.depends("reference", "name", "staff_id.display_name", "assignment_type", "start", "stop")
    def _compute_display_name(self):
        """Compute the assignment label from fields available in this active model."""
        type_selection = dict(self._fields["assignment_type"].selection)
        for rec in self:
            parts = []
            if rec.reference and rec.reference not in ("/",):
                parts.append(f"[{rec.reference}]")
            if rec.name:
                parts.append(rec.name)
            if rec.staff_id:
                parts.append(rec.staff_id.display_name or _("(No Staff)"))
            if rec.assignment_type:
                parts.append(f"→ {type_selection.get(rec.assignment_type, rec.assignment_type)}")
            if rec.start and rec.stop:
                parts.append(
                    f"({fields.Datetime.to_string(rec.start)} → {fields.Datetime.to_string(rec.stop)})"
                )
            rec.display_name = " ".join(parts) if parts else _("Staff Assignment")

