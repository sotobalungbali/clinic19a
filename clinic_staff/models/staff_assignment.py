    @api.depends("staff_id.license_ids.state")
    def _compute_license_flags(self):
        for rec in self:
            # tetap baca required_skill_ids di body; decorator tidak menyebutnya
            rec.license_required = any(skill.requires_license for skill in rec.required_skill_ids)
            rec.has_active_license = rec._get_staff_active_license(rec.staff_id) if rec.staff_id else False

    def _overlap_domain(self, start_dt, end_dt):
        return [("start", "<", end_dt), ("stop", ">", start_dt)]

    def _availability_conflict(self):
        """Cek konflik dengan availability blocking."""
        Av = self.env.get("clinic.staff.availability")
        AvOcc = self.env.get("clinic.staff.availability.occurrence")
        conflict = False
        for rec in self:
            if not (rec.staff_id and rec.start and rec.stop):
                continue
            try:
                if Av:
                    dom_av = [
                        ("staff_id", "=", rec.staff_id.id),
                        ("is_blocking", "=", True),
                    ] + self._overlap_domain(rec.start, rec.stop)
                    conflict = conflict or bool(Av.sudo().search_count(dom_av))
                if AvOcc:
                    dom_oc = [
                        ("staff_id", "=", rec.staff_id.id),
                        ("is_blocking", "=", True),
                        ("state", "in", ("planned", "applied")),
                    ] + self._overlap_domain(rec.start, rec.stop)
                    conflict = conflict or bool(AvOcc.sudo().search_count(dom_oc))
            except Exception:
                _logger.debug("Availability conflict check skipped for assignment %s", rec.id)
        return conflict

    def _compute_conflicts(self):
        for rec in self:
            # Overlap vs other assignments (same staff), except cancelled/done/closed
            dom_as = [
                ("id", "!=", rec.id),
                ("staff_id", "=", rec.staff_id.id),
                ("state", "in", ("draft", "confirmed", "in_progress", "paused")),
            ] + self._overlap_domain(rec.start, rec.stop)
            try:
                other_overlap = bool(self.sudo().search_count(dom_as))
            except Exception:
                other_overlap = False
            rec.conflict_other_assignments = (other_overlap and not rec.allow_overlap)

            # Availability blocking conflict
            rec.conflict_blocking_availability = False
            try:
                rec.conflict_blocking_availability = bool(self.browse(rec.id)._availability_conflict())
            except Exception:
                pass

    def _compute_within_roster(self):
        for rec in self:
            if rec.roster_id and rec.start and rec.stop:
                rec.within_roster = (rec.start >= rec.roster_id.start and rec.stop <= rec.roster_id.stop)
            else:
                rec.within_roster = False

    @api.depends("sla_target", "sla_deadline", "actual_start", "actual_stop")
    def _compute_sla_met(self):
        for rec in self:
            met = False
            if rec.sla_target == "start" and rec.sla_deadline and rec.actual_start:
                met = rec.actual_start <= rec.sla_deadline
            elif rec.sla_target == "finish" and rec.sla_deadline and rec.actual_stop:
                met = rec.actual_stop <= rec.sla_deadline
            rec.sla_met = met

    # =========================================================
    # Constraints
    # =========================================================
    @api.constrains("start", "stop")
    def _check_planned_window(self):
        for rec in self:
            if rec.start and rec.stop and rec.stop <= rec.start:
                raise ValidationError(_("Planned Stop must be later than Planned Start."))

    @api.constrains("actual_start", "actual_stop")
    def _check_actual_window(self):
        for rec in self:
            if rec.actual_start and rec.actual_stop and rec.actual_stop <= rec.actual_start:
                raise ValidationError(_("Actual Stop must be later than Actual Start."))

    @api.constrains("staff_id", "start", "stop", "state", "allow_overlap")
    def _check_overlap_other_assignments(self):
        """Larangan overlap assignment aktif kecuali allow_overlap=True."""
        for rec in self.filtered(lambda r: r.staff_id and r.start and r.stop and not r.allow_overlap):
            dom = [
                ("id", "!=", rec.id),
                ("staff_id", "=", rec.staff_id.id),
                ("state", "in", ("draft", "confirmed", "in_progress", "paused")),
            ] + self._overlap_domain(rec.start, rec.stop)
            if self.search_count(dom):
                raise ValidationError(_("This assignment overlaps with another active assignment for the same staff."))

