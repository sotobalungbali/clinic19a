    # MEMANG DI REMARK - DEPRECATED ERROR
    # Hilangkan 'required_skill_ids' dari depends untuk menghindari ValueError @depends
    @api.depends("staff_id.grade", "staff_id.license_ids.state")
    def _compute_compliance(self):
        """Skill compliance: semua required_skill harus ada di clinic.staff.skill dengan state 'valid'."""
        StaffSkill = self.env["clinic.staff.skill"]
        for rec in self:
            if not rec.required_skill_ids:
                rec.is_skill_compliant = True
                continue
            ok = True
            for skill in rec.required_skill_ids:
                has = StaffSkill.sudo().search_count([
                    ("staff_id", "=", rec.staff_id.id),
                    ("skill_id", "=", skill.id),
                    ("state", "=", "valid"),
                ])
                if not has:
                    ok = False
                    break
            rec.is_skill_compliant = bool(ok)

