    def _compute_durations(self):
        for rec in self:
            rec.planned_minutes = 0
            rec.actual_minutes = 0
            rec.effort_hours = 0.0
            if rec.start and rec.stop:
                rec.planned_minutes = max(0, int((rec.stop - rec.start).total_seconds() // 60))
            if rec.actual_start and rec.actual_stop:
                rec.actual_minutes = max(0, int((rec.actual_stop - rec.actual_start).total_seconds() // 60))
                rec.effort_hours = rec.actual_minutes / 60.0

    def _get_staff_active_license(self, staff):
        """Helper: cek ada lisensi aktif pada staff (state active/expiring & belum kadaluarsa)."""
        License = self.env["clinic.staff.license"]
        # Gunakan search_count cepat; asumsi expiry logic pada model lisensi
        return bool(License.sudo().search_count([
            ("staff_id", "=", staff.id),
            ("state", "in", ("active", "expiring")),
        ]))

