    def action_confirm(self):
        """Konfirmasi assignment: cek compliance & konflik mendasar."""
        for rec in self:
            if rec.state not in ("draft",):
                continue
            # Cek eligibility staff (dari model staff)
            rec.staff_id.ensure_clinical_eligibility()
            # Cek skill compliance minimal
            if rec.required_skill_ids and not rec.is_skill_compliant:
                raise ValidationError(_("Staff does not meet required skills for this assignment."))
            # Cek license jika perlu
            if rec.license_required and not rec.has_active_license:
                raise ValidationError(_("Active professional license is required for this assignment."))
            # Cek availability blocking
            if rec.conflict_blocking_availability:
                raise ValidationError(_("This assignment conflicts with blocking availability windows."))
            # Cek roster (opsional tapi disarankan)
            if rec.roster_id and not rec.within_roster:
                raise ValidationError(_("Planned window must be within the linked roster time range."))
            rec.state = "confirmed"
            rec.message_post(body=_("Assignment confirmed."))
        return True

    def action_start(self):
        """Mulai pengerjaan assignment."""
        for rec in self:
            if rec.state not in ("confirmed", "paused"):
                continue
            if not rec.actual_start:
                rec.actual_start = fields.Datetime.now()
            rec.state = "in_progress"
            rec.message_post(body=_("Assignment started."))
        return True

    def action_pause(self):
        """Jeda pengerjaan (opsional)."""
        for rec in self:
            if rec.state != "in_progress":
                continue
            rec.state = "paused"
            rec.message_post(body=_("Assignment paused."))
        return True

    def action_done(self):
        """Selesaikan assignment."""
        for rec in self:
            if rec.state not in ("in_progress", "paused", "confirmed"):
                continue
            if not rec.actual_stop:
                rec.actual_stop = fields.Datetime.now()
            rec.state = "done"
            # Tandai closed untuk konsistensi lifecycle (opsional)
            rec.message_post(body=_("Assignment completed."))
        return True

    def action_cancel(self):
        """Batalkan assignment."""
        for rec in self:
            if rec.state in ("done", "closed"):
                raise ValidationError(_("Completed assignments cannot be cancelled."))
            rec.state = "cancelled"
            rec.message_post(body=_("Assignment cancelled."))
        return True

    def action_close(self):
        """Tutup assignment (alias finalisasi setelah 'done')."""
        for rec in self:
            if rec.state != "done":
                continue
            rec.state = "closed"
            rec.message_post(body=_("Assignment closed."))
        return True

    # =========================================================
    # Reassignment / Helpers
    # =========================================================
    def reassign_to(self, new_staff_id):
        """Re-assign ke staff berbeda (dipanggil dari wizard/batch).
        - Memvalidasi eligibility staff baru.
        """
        Staff = self.env["clinic.staff"]
        new_staff = Staff.browse(new_staff_id).exists()
        if not new_staff:
            raise ValidationError(_("Target staff not found."))

        for rec in self:
            new_staff.ensure_clinical_eligibility()
            # Optional: reset compliance flag notifikasi
            rec.write({"staff_id": new_staff.id})
            rec.message_post(body=_("Assignment reassigned to %s.") % (new_staff.display_name,))
        return True

    # =========================================================
    # Name get
    # =========================================================
    def name_get(self):
        res = []
        for rec in self:
            res.append((rec.id, rec.display_name or rec.name or rec.reference or _("Assignment")))
        return res
