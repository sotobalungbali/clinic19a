    @api.model_create_multi
    def create(self, vals_list):
        """Set reference dari sequence, lakukan validasi ringan, dan schedule activity jika perlu."""
        for vals in vals_list:
            if not vals.get("reference") or vals.get("reference") in ("/",):
                vals["reference"] = self.env["ir.sequence"].next_by_code("clinic.staff.assignment") or "/"
        records = super().create(vals_list)

        # Jadwalkan activity jika compliance belum terpenuhi atau ada konflik availability
        for rec in records:
            # Compliance basic
            if rec.required_skill_ids and not rec.is_skill_compliant:
                rec.activity_schedule(
                    "mail.mail_activity_data_todo",
                    summary=_("Validate skill compliance"),
                    note=_("Staff may not meet all required skills for this assignment. Please review."),
                )
            if rec.license_required and not rec.has_active_license:
                rec.activity_schedule(
                    "mail.mail_activity_data_todo",
                    summary=_("Ensure active professional license"),
                    note=_("At least one required skill needs an active license. Please review staff licenses."),
                )
            # Availability blocking
            if rec.conflict_blocking_availability:
                rec.activity_schedule(
                    "mail.mail_activity_data_todo",
                    summary=_("Conflicts with blocking availability"),
                    note=_("This assignment overlaps with blocking availability windows. Please resolve."),
                )
        return records

