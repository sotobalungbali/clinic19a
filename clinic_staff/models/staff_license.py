# ============================================================
# Master License Type
# ============================================================
class ClinicLicenseType(models.Model):
    _name = "clinic.license.type"
    _description = "Clinic License Type"
    _rec_name = "name"
    _order = "sequence, name"

    # Urutan tampilan
    sequence = fields.Integer(
        string="Sequence",
        default=10,
        help="Defines the order of license types in lists and selections.",
    )

    # Identitas tipe lisensi
    name = fields.Char(
        string="License Type",
        required=True,
        index=True,
        translate=True,
        help="Human-readable name of the license type, e.g., 'Nurse Registration', 'Therapist Certification'.",
    )

    code = fields.Char(
        string="Code",
        required=True,
        copy=False,
        default="/",
        index=True,
        help="Unique license type code generated by sequence.",
    )

    description = fields.Text(
        string="Description",
        translate=True,
        help="Long description, coverage, or regulatory notes.",
    )

    # Applicability per role
    applicable_to_nurse = fields.Boolean(
        string="Applicable to Nurse", default=True,
        help="Mark if this license applies to Nurse role.",
    )
    applicable_to_therapist = fields.Boolean(
        string="Applicable to Therapist", default=True,
        help="Mark if this license applies to Therapist role.",
    )
    applicable_to_doctor = fields.Boolean(
        string="Applicable to Doctor", default=False,
        help="Mark if this license applies to Doctor role.",
    )

    # Aturan masa berlaku & notifikasi
    validity_months = fields.Integer(
        string="Validity (Months)",
        default=0,
        help="Default validity period in months used to auto-compute Expiry Date from Issue Date. "
             "Set 0 if there is no default validity.",
    )

    renewal_notice_days = fields.Integer(
        string="Renewal Notice (Days)",
        default=30,
        help="Number of days before expiry when the license should be considered 'Expiring' "
             "and renewal reminders are triggered.",
    )

    requires_number = fields.Boolean(
        string="Requires License Number",
        default=True,
        help="If enabled, the license number becomes mandatory on staff licenses.",
    )
    requires_issuer = fields.Boolean(
        string="Requires Issuer",
        default=False,
        help="If enabled, issuer fields become mandatory on staff licenses.",
    )
    requires_country = fields.Boolean(
        string="Requires Country/Region",
        default=False,
        help="If enabled, country/state must be specified on staff licenses.",
    )
    requires_attachment = fields.Boolean(
        string="Requires Attachment",
        default=False,
        help="If enabled, at least one supporting document attachment is required.",
    )

    # Multi-company support
    company_id = fields.Many2one(
        "res.company",
        string="Company",
        default=lambda self: self.env.company,
        help="Company for which this license type applies.",
    )

    is_active = fields.Boolean(
        string="Active",
        default=True,
        help="If unchecked, this license type will be hidden from selection.",
    )

    # Back references
    staff_license_ids = fields.One2many(
        "clinic.staff.license",
        "license_type_id",
        string="Staff Licenses",
        help="Staff license records that use this license type.",
    )

    _license_type_code_unique = models.Constraint(
        'unique(code)',
        'License Type Code must be unique.',
    )

    _license_type_name_company_unique = models.Constraint(
        'unique(name, company_id)',
        'License Type name must be unique per company.',
    )

    @api.model_create_multi
    def create(self, vals_list):
        """Generate sequence untuk code jika '/'. """
        for vals in vals_list:
            if not vals.get("code") or vals.get("code") in ("/",):
                vals["code"] = self.env["ir.sequence"].next_by_code("clinic.license.type") or "/"
        return super().create(vals_list)


