    # =========================
    # Compute helpers
    # =========================
    @api.depends("reference", "staff_id.display_name", "license_type_id.name", "number")
    def _compute_display_name(self):
        """Bangun label tampilan gabungan."""
        for rec in self:
            parts = []
            if rec.reference and rec.reference not in ("/",):
                parts.append(f"[{rec.reference}]")
            if rec.staff_id:
                parts.append(rec.staff_id.display_name or _("(No Staff)"))
            if rec.license_type_id:
                parts.append(f"- {rec.license_type_id.name}")
            if rec.number:
                parts.append(f"({rec.number})")
            rec.display_name = " ".join(parts) if parts else _("Staff License")

    def _today(self):
        """Abstraksi tanggal hari ini agar mudah di-mock di unit test."""
        return fields.Date.context_today(self)

    @api.depends("expiry_date", "license_type_id.renewal_notice_days")
    def _compute_dates_flags(self):
        """Hitung sisa hari ke expiry dan flag expiring window."""
        today = self._today()
        for rec in self:
            rec.days_to_expiry = 0
            rec.is_expiring_window = False
            if rec.expiry_date:
                delta = rec.expiry_date - today
                rec.days_to_expiry = delta.days
                window = rec.license_type_id.renewal_notice_days or 0
                rec.is_expiring_window = (0 <= delta.days <= window)

    def _compute_attachment_count(self):
        for rec in self:
            rec.attachment_count = len(rec.attachment_ids)

    # =========================
    # Onchange & Defaults
    # =========================
    @api.onchange("issue_date", "license_type_id")
    def _onchange_dates_by_type(self):
        """Auto hitung expiry dari issue + validity_months jika expiry belum diisi."""
        for rec in self:
            if rec.issue_date and rec.license_type_id and not rec.expiry_date:
                months = rec.license_type_id.validity_months or 0
                if months > 0:
                    # Gunakan utilitas add_months sederhana (approx via relativedelta jika tersedia)
                    try:
                        from dateutil.relativedelta import relativedelta
                        rec.expiry_date = rec.issue_date + relativedelta(months=+months)
                    except Exception:
                        # Fallback kasar: 30 hari x months
                        rec.expiry_date = rec.issue_date + timedelta(days=30 * months)

    # =========================
    # Lifecycle helpers
    # =========================
    def _recompute_state_by_dates(self):
        """Evaluasi status berdasarkan tanggal kadaluarsa dan window expiring."""
        today = self._today()
        for rec in self:
            if rec.state in ("archived", "suspended"):
                # Jangan override status manual yang bersifat final/transient
                continue
            if rec.expiry_date:
                if rec.expiry_date < today:
                    new_state = "expired"
                else:
                    # Aktif atau masuk window expiring
                    if rec.is_expiring_window:
                        new_state = "expiring"
                    else:
                        new_state = "active"
            else:
                # Tanpa expiry, jika sudah issue_date maka active, selainnya draft
                new_state = "active" if rec.issue_date else "draft"

            if rec.state != new_state:
                rec.state = new_state

    def _maybe_schedule_expiry_activity(self):
        """Jadwalkan activity untuk pengingat perpanjangan jika masuk window expiring."""
        for rec in self:
            if not rec.expiry_date:
                continue
            if rec.state not in ("active", "expiring"):
                continue
            try:
                notice_days = rec.license_type_id.renewal_notice_days or 0
                if notice_days <= 0:
                    continue
                deadline = rec.expiry_date - timedelta(days=notice_days)
                if deadline and deadline >= self._today():
                    rec.activity_schedule(
                        "mail.mail_activity_data_todo",
                        date_deadline=deadline,
                        summary=_("Renew license before expiry"),
                        note=_(
                            "License '%(name)s' will expire on %(date)s. "
                            "Please start the renewal process."
                        ) % {"name": rec.display_name, "date": rec.expiry_date},
                    )
            except Exception as e:
                _logger.warning("Failed to schedule renewal activity for %s: %s", rec.display_name, e)

    # =========================
    # CRUD overrides
    # =========================
    @api.model_create_multi
    def create(self, vals_list):
        """Set reference dari sequence, validasi isian wajib sesuai tipe, dan evaluasi status."""
        records = self.browse()
        for vals in vals_list:
            if not vals.get("reference") or vals.get("reference") in ("/",):
                vals["reference"] = self.env["ir.sequence"].next_by_code("clinic.staff.license") or "/"
        records = super().create(vals_list)

        # Validasi isian wajib (berdasarkan tipe)
        for rec in records:
            rec._validate_required_by_type()
            rec._recompute_state_by_dates()
            rec._maybe_schedule_expiry_activity()

            # Jika tipe mengharuskan attachment dan belum ada -> buat activity
            if rec.license_type_id.requires_attachment and not rec.attachment_ids:
                rec.activity_schedule(
                    "mail.mail_activity_data_todo",
                    summary=_("Attach supporting documents"),
                    note=_("This license type requires at least one supporting attachment."),
                )
        return records

    def write(self, vals):
        """Re-evaluasi status dan aktivitas pengingat saat tanggal/tipe berubah."""
        res = super().write(vals)

        # Validasi isian wajib jika fields kunci berubah
        keys = {"license_type_id", "number", "issuer", "issuer_partner_id", "country_id", "state_id"}
        if keys.intersection(vals.keys()):
            for rec in self:
                rec._validate_required_by_type()

        # Evaluasi status & activity bila tanggal berubah
        if {"issue_date", "expiry_date", "license_type_id"}.intersection(vals.keys()):
            for rec in self:
                rec._recompute_state_by_dates()
                rec._maybe_schedule_expiry_activity()
        return res

    # =========================
    # Business validations
    # =========================
    def _validate_required_by_type(self):
        """Validasi kewajiban field berdasarkan aturan pada License Type."""
        for rec in self:
            lt = rec.license_type_id
            if not lt:
                continue
            # number wajib?
            if lt.requires_number and not rec.number:
                raise ValidationError(_("License Number is required for this License Type."))
            # issuer wajib?
            if lt.requires_issuer and not (rec.issuer or rec.issuer_partner_id):
                raise ValidationError(_("Issuer is required for this License Type (name or partner)."))
            # negara/wilayah wajib?
            if lt.requires_country and not rec.country_id:
                raise ValidationError(_("Country is required for this License Type."))
            # attachment wajib? (diperiksa di create; disini validasi juga saat write)
            if lt.requires_attachment and not rec.attachment_ids:
                # Tidak raise langsung agar tidak menghambat update; gunakan activity.
                self.activity_schedule(
                    "mail.mail_activity_data_todo",
                    summary=_("Attach supporting documents"),
                    note=_("This license type requires at least one supporting attachment."),
                )

    @api.constrains("issue_date", "expiry_date")
    def _check_dates(self):
        for rec in self:
            if rec.issue_date and rec.expiry_date and rec.expiry_date < rec.issue_date:
                raise ValidationError(_("Expiry Date cannot be earlier than Issue Date."))

    # =========================
    # Actions (UI / Wizards)
    # =========================
    def action_mark_verified(self):
        """Tandai lisensi sebagai terverifikasi."""
        for rec in self:
            rec.write({
                "verified": True,
                "verified_on": fields.Datetime.now(),
                "verified_by": self.env.user.id,
            })
        return True

    def action_set_draft(self):
        """Kembalikan status ke Draft (kecuali archived)."""
        for rec in self:
            if rec.state == "archived":
                raise ValidationError(_("Cannot revert from Archived to Draft."))
            rec.state = "draft"
        return True

    def action_activate(self):
        """Set status Active (atau Expiring jika sudah masuk window)."""
        for rec in self:
            if rec.state == "archived":
                raise ValidationError(_("Cannot activate an Archived license."))
            rec._recompute_state_by_dates()
            if rec.state in ("draft", "expired", "suspended"):
                # Paksa ke active jika memenuhi syarat tanggal
                if rec.expiry_date:
                    today = rec._today()
                    if rec.expiry_date < today:
                        raise ValidationError(_("Cannot activate an expired license. Please renew."))
                    rec.state = "expiring" if rec.is_expiring_window else "active"
                else:
                    rec.state = "active"
            rec._maybe_schedule_expiry_activity()
        return True

    def action_suspend(self):
        """Tangguhkan lisensi (mis. pelanggaran/komplain)."""
        for rec in self:
            if rec.state == "archived":
                raise ValidationError(_("Cannot suspend an Archived license."))
            rec.state = "suspended"
        return True

    def action_archive(self):
        """Arsipkan lisensi (menonaktifkan secara final)."""
        for rec in self:
            rec.state = "archived"
            rec.active = False
        return True

    def action_open_attachments(self):
        """Buka lampiran bukti lisensi."""
        self.ensure_one()
        return {
            "name": _("Attachments"),
            "type": "ir.actions.act_window",
            "res_model": "ir.attachment",
            "view_mode": "kanban,list,form",
            "domain": [("id", "in", self.attachment_ids.ids)],
            "context": {"default_res_model": self._name, "default_res_id": self.id},
        }

    def action_open_renewal_wizard(self):
        """Buka wizard renewal (jika modul wizard tersedia), fallback ke form jika tidak ada."""
        self.ensure_one()
        Wizard = self.env.get("clinic.staff.license.renewal.wizard")
        if Wizard:
            # Buka wizard standar
            return {
                "name": _("Renew License"),
                "type": "ir.actions.act_window",
                "res_model": "clinic.staff.license.renewal.wizard",
                "view_mode": "form",
                "target": "new",
                "context": {"default_license_id": self.id},
            }
        # Fallback: buka record form untuk perpanjangan manual
        return {
            "name": _("License"),
            "type": "ir.actions.act_window",
            "res_model": "clinic.staff.license",
            "view_mode": "form",
            "res_id": self.id,
            "target": "current",
        }

    # =========================
    # Integration helpers
    # =========================
    def is_currently_valid(self):
        """True jika status 'active'/'expiring' dan belum melewati expiry_date."""
        today = self._today()
        for rec in self:
            if rec.state in ("active", "expiring"):
                if rec.expiry_date and rec.expiry_date < today:
                    return False
                return True
        return False

    def contributes_to_staff_eligibility(self):
        """Dipakai modul lain untuk cek eligibility klinis (soft contract)."""
        # Lisensi dinilai berkontribusi jika state active/expiring (belum kadaluarsa).
        return any(self.filtered(lambda l: l.is_currently_valid()))

    # =========================
    # Name get
    # =========================
    def name_get(self):
        res = []
        for rec in self:
            name = rec.display_name or rec.reference or _("Staff License")
            res.append((rec.id, name))
        return res
