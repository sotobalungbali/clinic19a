    # -------------------------
    # Constraints
    # -------------------------
    @api.constrains("start", "stop", "staff_id", "state")
    def _check_overlap_basic(self):
        """Cegah dua roster overlap pada staff yang sama saat status aktif (published or beyond)."""
        for rec in self.filtered(lambda r: r.state in ("published", "in_progress")):
            domain = [
                ("id", "!=", rec.id),
                ("staff_id", "=", rec.staff_id.id),
                ("state", "in", ("published", "in_progress")),
            ] + self._overlap_domain(rec.start, rec.stop)
            if self.search_count(domain):
                raise ValidationError(_("This roster overlaps with another active roster for the same staff."))

    # -------------------------
    # Utility
    # -------------------------
    def _staff_is_eligible(self):
        """Gunakan helper dari model staff (can_be_scheduled)."""
        for rec in self:
            if not rec.staff_id.can_be_scheduled:
                raise ValidationError(
                    _("Staff '%s' is not eligible for clinical scheduling.") % (rec.staff_id.display_name,)
                )
        return True

    def _ensure_no_blocking_availability(self):
        """Prevent publishing a roster that overlaps blocking availability."""
        Availability = self.env.get("clinic.staff.availability")
        Occurrence = self.env.get("clinic.staff.availability.occurrence")
        for rec in self:
            conflict = False
            if "conflict_availability" in rec._fields:
                conflict = bool(rec.conflict_availability)
            elif rec.staff_id and rec.start and rec.stop:
                if Availability:
                    conflict = bool(Availability.sudo().search_count([
                        ("staff_id", "=", rec.staff_id.id),
                        ("is_blocking", "=", True),
                        ("active", "=", True),
                        ("start", "<", rec.stop),
                        ("stop", ">", rec.start),
                    ]))
                if not conflict and Occurrence:
                    conflict = bool(Occurrence.sudo().search_count([
                        ("staff_id", "=", rec.staff_id.id),
                        ("is_blocking", "=", True),
                        ("state", "in", ("planned", "applied")),
                        ("start", "<", rec.stop),
                        ("stop", ">", rec.start),
                    ]))
            if conflict:
                raise ValidationError(
                    _("This roster conflicts with blocking availability windows. Please resolve availability first.")
                )
        return True

    # -------------------------
    # Actions / Workflow
    # -------------------------
    def action_publish(self):
        """Terbitkan roster: validasi eligibility & konflik, set published_on/by."""
        for rec in self:
            if rec.state not in ("draft",):
                continue
            rec._staff_is_eligible()
            rec._ensure_no_blocking_availability()

            rec.write({
                "state": "published",
                "published_on": fields.Datetime.now(),
                "published_by": self.env.user.id,
            })
            rec.message_post(body=_("Roster published."))
        return True

    def action_start(self):
        """Mulai shift (In Progress)."""
        now = fields.Datetime.now()
        for rec in self:
            if rec.state not in ("published",):
                continue
            if rec.start and now < rec.start - timedelta(minutes=30):
                # optional: cegah start terlalu dini
                pass
            rec.state = "in_progress"
            rec.message_post(body=_("Roster in progress."))
        return True

    def action_complete(self):
        """Selesaikan shift (Completed)."""
        for rec in self:
            if rec.state not in ("in_progress",):
                continue
            rec.state = "completed"
            rec.message_post(body=_("Roster completed."))
        return True

    def action_cancel(self):
        """Batalkan roster."""
        for rec in self:
            if rec.state in ("completed",):
                raise ValidationError(_("Completed roster cannot be cancelled."))
            rec.state = "cancelled"
            rec.message_post(body=_("Roster cancelled."))
        return True

    def action_reopen(self):
        """Kembalikan ke Draft (jika belum completed)."""
        for rec in self:
            if rec.state == "completed":
                raise ValidationError(_("Completed roster cannot be reopened."))
            rec.state = "draft"
            rec.message_post(body=_("Roster set back to Draft."))
        return True

    # -------------------------
    # Generator from Template
    # -------------------------
    def _float_hour_to_daytime(self, base_date: datetime, hour_float: float) -> datetime:
        """Konversi jam float (8.5 -> 08:30) menjadi datetime pada tanggal tertentu (UTC)."""
        hour = int(hour_float)
        minutes = int(round((hour_float - hour) * 60))
        return base_date.replace(hour=hour, minute=minutes, second=0, microsecond=0)

    @api.model
    def generate_from_template(self, template_id, staff_ids, date_from, date_to, branch_id=False, role=False):
        """Generate roster dari template pada rentang tanggal untuk beberapa staff.
        - Menghormati hari aktif template.
        - Tidak memaksa cek availability; publish dilakukan terpisah.
        - Menghindari duplikasi (cek overlap exact untuk staff pada jam sama).
        Return: jumlah roster dibuat.
        """
        if not template_id or not staff_ids or not date_from or not date_to:
            return 0

        template = self.env["clinic.shift.template"].browse(template_id)
        if not template.exists():
            return 0

        created = 0
        # Iterasi setiap hari dalam rentang
        day = date_from
        while day <= date_to:
            if template._is_active_weekday(day):
                start_dt = self._float_hour_to_daytime(day, template.start_time)
                stop_dt = start_dt + timedelta(hours=template.duration_hours)

                for staff in self.env["clinic.staff"].browse(staff_ids).exists():
                    vals = {
                        "staff_id": staff.id,
                        "template_id": template.id,
                        "branch_id": branch_id or False,
                        "role": role or (staff.role if staff.role in ("nurse", "therapist", "doctor") else "other"),
                        "start": start_dt,
                        "stop": stop_dt,
                        "state": "draft",
                        "color": template.color or 0,
                    }
                    # Cegah duplikasi exact time window untuk staff yang sama
                    exists = self.search_count([
                        ("staff_id", "=", staff.id),
                        ("start", "=", start_dt),
                        ("stop", "=", stop_dt),
                        ("state", "!=", "cancelled"),
                    ])
                    if not exists:
                        self.create(vals)
                        created += 1
            day = day + timedelta(days=1)
        return created

    # -------------------------
    # Name get
    # -------------------------
    def name_get(self):
        res = []
        for rec in self:
            name = rec.display_name or _("Staff Roster")
            res.append((rec.id, name))
        return res

