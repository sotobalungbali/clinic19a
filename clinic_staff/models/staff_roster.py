class ClinicShiftTemplate(models.Model):
    _name = "clinic.shift.template"
    _description = "Shift Template"
    _rec_name = "name"
    _order = "sequence, name"

    sequence = fields.Integer(
        string="Sequence",
        default=10,
        help="Ordering of shift templates in lists and pickers.",
    )

    name = fields.Char(
        string="Template Name",
        required=True,
        translate=True,
        help="Human-readable name, e.g., 'Morning', 'Afternoon', 'Night', 'Weekend'.",
    )

    code = fields.Char(
        string="Code",
        required=True,
        copy=False,
        default="/",
        index=True,
        help="Unique code generated by sequence for shift template.",
    )

    # Jam mulai & durasi (jam) — dipakai untuk membentuk start/stop roster harian
    start_time = fields.Float(
        string="Start Time (Hours)",
        required=True,
        help="Hour-of-day in 24h format (e.g., 8.0 = 08:00, 13.5 = 13:30).",
    )
    duration_hours = fields.Float(
        string="Duration (Hours)",
        required=True,
        help="Duration of the shift in hours (e.g., 8.0).",
    )

    # Hari aktif: template dapat dibatasi ke hari tertentu (untuk generator)
    active_mon = fields.Boolean("Mon", default=True)
    active_tue = fields.Boolean("Tue", default=True)
    active_wed = fields.Boolean("Wed", default=True)
    active_thu = fields.Boolean("Thu", default=True)
    active_fri = fields.Boolean("Fri", default=True)
    active_sat = fields.Boolean("Sat", default=False)
    active_sun = fields.Boolean("Sun", default=False)

    role_applicability = fields.Selection(
        selection=[
            ("any", "Any"),
            ("nurse", "Nurse"),
            ("therapist", "Therapist"),
            ("doctor", "Doctor"),
        ],
        string="Role Applicability",
        default="any",
        help="If set, the shift is intended for a specific role.",
    )

    # default_branch_id = fields.Many2one(
    #     "clinic.branch",
    #     string="Default Branch",
    #     help="Default branch where this shift template is typically used.",
    # )

    color = fields.Integer(
        string="Color",
        help="Optional color index for calendar views.",
    )

    company_id = fields.Many2one(
        "res.company",
        string="Company",
        default=lambda self: self.env.company,
        help="Company context for the shift template.",
    )

    is_active = fields.Boolean(
        string="Active",
        default=True,
        help="If unchecked, this template will be hidden from selection.",
    )

    _shift_template_code_unique = models.Constraint(
        'unique(code)',
        'Shift Template Code must be unique.',
    )

    _shift_template_name_company_unique = models.Constraint(
        'unique(name, company_id)',
        'Shift Template name must be unique per company.',
    )

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if not vals.get("code") or vals.get("code") in ("/",):
                vals["code"] = self.env["ir.sequence"].next_by_code("clinic.shift.template") or "/"
        return super().create(vals_list)

    # Utility: apakah hari aktif?
    def _is_active_weekday(self, dt: datetime) -> bool:
        self.ensure_one()
        idx = dt.weekday()  # 0=Mon..6=Sun
        return [
            self.active_mon, self.active_tue, self.active_wed, self.active_thu,
            self.active_fri, self.active_sat, self.active_sun
        ][idx]


