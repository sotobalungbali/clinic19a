# Workload Policy (Master)
# ============================================================
class ClinicWorkloadPolicy(models.Model):
    _name = "clinic.workload.policy"
    _description = "Workload Policy"
    _rec_name = "name"
    _order = "sequence, date_start desc, id desc"

    sequence = fields.Integer(
        string="Sequence",
        default=10,
        help="Ordering of policies when multiple entries could apply."
    )

    name = fields.Char(
        string="Policy Name",
        required=True,
        translate=True,
        help="Human-readable name of this workload policy."
    )

    code = fields.Char(
        string="Code",
        required=True,
        copy=False,
        default="/",
        index=True,
        help="Unique code generated by sequence for the policy."
    )

    company_id = fields.Many2one(
        "res.company",
        string="Company",
        default=lambda self: self.env.company,
        help="Company where this policy applies."
    )

    # Cakupan (Scope)
    role_scope = fields.Selection(
        selection=[
            ("any", "Any"),
            ("nurse", "Nurse"),
            ("therapist", "Therapist"),
            ("doctor", "Doctor"),
            ("other", "Other"),
        ],
        string="Role Scope",
        default="any",
        index=True,
        help="Limit this policy to staff with a specific role, or apply to any role."
    )

    grade_scope = fields.Selection(
        selection=[
            ("any", "Any"),
            ("junior", "Junior"),
            ("mid", "Mid"),
            ("senior", "Senior"),
            ("lead", "Lead"),
            ("principal", "Principal"),
        ],
        string="Grade Scope",
        default="any",
        index=True,
        help="Limit this policy to a specific grade, or apply to any grade."
    )

    branch_id = fields.Many2one(
        "clinic.branch",
        string="Branch Scope",
        help="If set, this policy applies only to this branch."
    )

    # Kapasitas dasar
    weekly_capacity_hours = fields.Float(
        string="Weekly Capacity (Hours)",
        required=True,
        default=40.0,
        help="Nominal FTE weekly capacity in hours (e.g., 40.0)."
    )

    # Buffer & threshold
    buffer_percent = fields.Float(
        string="Buffer (%)",
        default=10.0,
        help="Buffer percentage for overload tolerance (e.g., 10%)."
    )

    warn_under_util_pct = fields.Float(
        string="Warn Under-Utilization (%)",
        default=60.0,
        help="Warn when planned/actual utilization falls below this percentage."
    )

    warn_over_util_pct = fields.Float(
        string="Warn Over-Utilization (%)",
        default=110.0,
        help="Warn when planned/actual utilization exceeds this percentage."
    )

    include_overtime = fields.Boolean(
        string="Include Overtime",
        default=True,
        help="If enabled, hours beyond roster/assignment windows will be counted as overtime if captured."
    )

    # Periode berlaku
    date_start = fields.Date(
        string="Valid From",
        help="Start date when the policy becomes effective (inclusive)."
    )

    date_end = fields.Date(
        string="Valid Until",
        help="End date when the policy stops being effective (inclusive)."
    )

    active = fields.Boolean(
        string="Active",
        default=True,
        help="If unchecked, this policy is ignored."
    )

    _workload_policy_code_unique = models.Constraint(
        'unique(code)',
        'Policy Code must be unique.',
    )

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if not vals.get("code") or vals.get("code") in ("/",):
                vals["code"] = self.env["ir.sequence"].next_by_code("clinic.workload.policy") or "/"
        return super().create(vals_list)

    # Seleksi policy yang applicable untuk staff & tanggal
    def is_applicable(self, staff, d_from=None, d_to=None):
        self.ensure_one()
        if not self.active:
            return False
        # Role
        if self.role_scope != "any" and staff.role != self.role_scope:
            return False
        # Grade
        if self.grade_scope != "any" and (staff.grade or "any") != self.grade_scope:
            return False
        # Branch
        if self.branch_id and staff.branch_id and (self.branch_id.id != staff.branch_id.id):
            return False
        # Date range (overlap hari)
        if self.date_start and d_to and fields.Date.to_date(self.date_start) > fields.Date.to_date(d_to):
            return False
        if self.date_end and d_from and fields.Date.to_date(self.date_end) < fields.Date.to_date(d_from):
            return False
        return True


