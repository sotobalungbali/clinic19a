    # --------------------------------------------------------
    # Compute
    # --------------------------------------------------------
    @api.depends("staff_id.display_name", "period_type", "date_from", "date_to")
    def _compute_display_name(self):
        for rec in self:
            period = dict(self._fields["period_type"].selection).get(rec.period_type)
            parts = [
                rec.staff_id.display_name or _("(No Staff)"),
                f"- {period}" if period else "",
                f"[{rec.date_from} → {rec.date_to}]",
            ]
            rec.display_name = " ".join([p for p in parts if p])

    # --------------------------------------------------------
    # Helper: Ambil policy applicable
    # --------------------------------------------------------
    def _pick_applicable_policy(self):
        Policy = self.env["clinic.workload.policy"]
        policies = Policy.search([("active", "=", True)], order="sequence, id")
        for rec in self:
            chosen = None
            for p in policies:
                if p.is_applicable(rec.staff_id, rec.date_from, rec.date_to):
                    chosen = p
                    break
            rec.policy_id = chosen

    # --------------------------------------------------------
    # Perhitungan kapasitas berdasarkan policy & panjang periode
    # --------------------------------------------------------
    def _compute_capacity_hours(self):
        for rec in self:
            if not rec.policy_id:
                rec.capacity_hours = 0.0
                continue
            # Skala berdasar jumlah hari dalam periode / 7 * weekly_capacity_hours
            d_from = fields.Date.to_date(rec.date_from)
            d_to = fields.Date.to_date(rec.date_to)
            days = (d_to - d_from).days + 1
            weekly = rec.policy_id.weekly_capacity_hours or 0.0
            # Asumsi kalender sederhana tanpa holiday: capacity ~ weekly * (days / 7)
            rec.capacity_hours = round(weekly * (float(days) / 7.0), 2)

    # --------------------------------------------------------
    # Sumber data (Roster/Assignment/Availability)
    # --------------------------------------------------------
    def _gather_source_minutes(self):
        """Kumpulkan menit planned/actual/leave per periode dari Roster, Assignment, Availability."""
        Roster = self.env.get("clinic.staff.roster")
        Assign = self.env.get("clinic.staff.assignment")
        Av = self.env.get("clinic.staff.availability")
        AvOcc = self.env.get("clinic.staff.availability.occurrence")

        for rec in self:
            if not (rec.staff_id and rec.date_from and rec.date_to):
                rec.planned_hours = rec.actual_hours = rec.leave_hours = rec.overtime_hours = 0.0
                continue

            # Range waktu (gunakan UTC; Date → Datetime 00:00 sampai 23:59:59)
            start_dt = fields.Datetime.to_datetime(f"{rec.date_from} 00:00:00")
            end_dt = fields.Datetime.to_datetime(f"{rec.date_to} 23:59:59")

            planned_min = 0
            actual_min = 0
            leave_min = 0
            overtime_min = 0

            # ---- Roster: planned hours
            if Roster:
                ros = Roster.sudo().search([
                    ("staff_id", "=", rec.staff_id.id),
                    ("state", "in", ("published", "in_progress", "completed")),
                    ("start", "<=", end_dt),
                    ("stop", ">=", start_dt),
                ])
                for r in ros:
                    planned_min += _overlap_minutes(r.start, r.stop, start_dt, end_dt)

            # ---- Assignment: planned vs actual
            if Assign:
                asg = Assign.sudo().search([
                    ("staff_id", "=", rec.staff_id.id),
                    ("state", "not in", ("cancelled", "closed")),
                    ("start", "<=", end_dt),
                    ("stop", ">=", start_dt),
                ])
                for a in asg:
                    # planned
                    planned_min += _overlap_minutes(a.start, a.stop, start_dt, end_dt)
                    # actual (jika tersedia; fallback planned jika in_progress/done tanpa actual)
                    if a.actual_start and a.actual_stop:
                        actual_min += _overlap_minutes(a.actual_start, a.actual_stop, start_dt, end_dt)
                    elif a.state in ("in_progress", "done") and (a.actual_start or a.actual_stop):
                        # partial actual: gunakan timestamp yang ada + planned sisi lain
                        st = a.actual_start or a.start
                        sp = a.actual_stop or a.stop
                        actual_min += _overlap_minutes(st, sp, start_dt, end_dt)

            # ---- Availability: Leave/Unavailable
            def add_leave_interval(s, e):
                nonlocal leave_min
                leave_min += _overlap_minutes(s, e, start_dt, end_dt)

            if Av:
                avs = Av.sudo().search([
                    ("staff_id", "=", rec.staff_id.id),
                    ("is_blocking", "=", True),
                    ("availability_type", "in", ("leave", "unavailable")),
                    ("start", "<=", end_dt),
                    ("stop", ">=", start_dt),
                ])
                for av in avs:
                    add_leave_interval(av.start, av.stop)

            if AvOcc:
                ovs = AvOcc.sudo().search([
                    ("staff_id", "=", rec.staff_id.id),
                    ("is_blocking", "=", True),
                    ("availability_type", "in", ("leave", "unavailable")),
                    ("state", "in", ("planned", "applied")),
                    ("start", "<=", end_dt),
                    ("stop", ">=", start_dt),
                ])
                for ov in ovs:
                    add_leave_interval(ov.start, ov.stop)

            # ---- Overtime: heuristik (optional)
            # Jika actual > planned dan policy include_overtime -> selisih dianggap overtime.
            if actual_min > planned_min:
                overtime_min = actual_min - planned_min

            rec.planned_hours = _to_hours(planned_min)
            rec.actual_hours = _to_hours(actual_min) if actual_min else (rec.planned_hours or 0.0)
            rec.leave_hours = _to_hours(leave_min)
            rec.overtime_hours = _to_hours(overtime_min)

    # --------------------------------------------------------
    # Hitung utilization & flags
    # --------------------------------------------------------
    def _compute_utilization_and_flags(self):
        for rec in self:
            cap = rec.capacity_hours or 0.0
            pol = rec.policy_id
            if cap <= 0:
                rec.utilization_planned = 0.0
                rec.utilization_actual = 0.0
                rec.under_utilized = False
                rec.over_utilized = False
                continue

            rec.utilization_planned = round((rec.planned_hours / cap) * 100.0, 2)
            rec.utilization_actual = round((rec.actual_hours / cap) * 100.0, 2)

            under_thr = (pol.warn_under_util_pct if pol else 0.0) or 0.0
            over_thr = (pol.warn_over_util_pct if pol else 0.0) or 100.0
            buffer_pct = (pol.buffer_percent if pol else 0.0) or 0.0

            rec.under_utilized = rec.utilization_actual < under_thr
            # Over-utilized jika planned/actual melewati threshold; buffer membuat ambang lebih permisif
            permitted = 100.0 + buffer_pct
            check_value = max(rec.utilization_planned, rec.utilization_actual)
            rec.over_utilized = check_value > max(over_thr, permitted)

    # --------------------------------------------------------
    # Public API
    # --------------------------------------------------------
    def recompute_workload(self, generate_lines=True, replace_lines=True):
        """Hitung ulang policy, capacity, sumber jam, dan utilization. Opsional generate workload lines."""
        Line = self.env["clinic.staff.workload.line"].sudo()
        for rec in self:
            # Policy & capacity
            rec._pick_applicable_policy()
            rec._compute_capacity_hours()
            # Hours breakdown
            rec._gather_source_minutes()
            # Utilization & flags
            rec._compute_utilization_and_flags()

            if generate_lines:
                if replace_lines and rec.line_ids:
                    rec.line_ids.unlink()
                rec._generate_detail_lines()

        return True

    def _generate_detail_lines(self):
        """Bangun baris detail dari sumber Roster/Assignment/Availability untuk audit."""
        Roster = self.env.get("clinic.staff.roster")
        Assign = self.env.get("clinic.staff.assignment")
        Av = self.env.get("clinic.staff.availability")
        AvOcc = self.env.get("clinic.staff.availability.occurrence")
        Line = self.env["clinic.staff.workload.line"].sudo()

        for rec in self:
            start_dt = fields.Datetime.to_datetime(f"{rec.date_from} 00:00:00")
            end_dt = fields.Datetime.to_datetime(f"{rec.date_to} 23:59:59")
            vals_batch = []

            # Roster
            if Roster:
                ros = Roster.sudo().search([
                    ("staff_id", "=", rec.staff_id.id),
                    ("state", "in", ("published", "in_progress", "completed")),
                    ("start", "<=", end_dt),
                    ("stop", ">=", start_dt),
                ])
                for r in ros:
                    minutes = _overlap_minutes(r.start, r.stop, start_dt, end_dt)
                    if minutes > 0:
                        vals_batch.append({
                            "workload_id": rec.id,
                            "source_type": "roster",
                            "source_ref": f"{r._name},{r.id}",
                            "start": r.start,
                            "stop": r.stop,
                            "minutes": minutes,
                            "state": r.state,
                            "branch_id": r.branch_id.id if r.branch_id else False,
                        })

            # Assignment
            if Assign:
                asg = Assign.sudo().search([
                    ("staff_id", "=", rec.staff_id.id),
                    ("state", "not in", ("cancelled", "closed")),
                    ("start", "<=", end_dt),
                    ("stop", ">=", start_dt),
                ])
                for a in asg:
                    pmin = _overlap_minutes(a.start, a.stop, start_dt, end_dt)
                    amin = 0
                    if a.actual_start and a.actual_stop:
                        amin = _overlap_minutes(a.actual_start, a.actual_stop, start_dt, end_dt)
                    elif a.state in ("in_progress", "done") and (a.actual_start or a.actual_stop):
                        st = a.actual_start or a.start
                        sp = a.actual_stop or a.stop
                        amin = _overlap_minutes(st, sp, start_dt, end_dt)

                    if pmin > 0:
                        vals_batch.append({
                            "workload_id": rec.id,
                            "source_type": "assignment_planned",
                            "source_ref": f"{a._name},{a.id}",
                            "start": a.start,
                            "stop": a.stop,
                            "minutes": pmin,
                            "state": a.state,
                            "branch_id": a.branch_id.id if a.branch_id else False,
                        })
                    if amin > 0:
                        vals_batch.append({
                            "workload_id": rec.id,
                            "source_type": "assignment_actual",
                            "source_ref": f"{a._name},{a.id}",
                            "start": a.actual_start or a.start,
                            "stop": a.actual_stop or a.stop,
                            "minutes": amin,
                            "state": a.state,
                            "branch_id": a.branch_id.id if a.branch_id else False,
                        })

            # Availability (Leave/Unavailable)
            def add_av_line(src, s, e, minutes, state=None, branch=None):
                if minutes <= 0:
                    return
                vals_batch.append({
                    "workload_id": rec.id,
                    "source_type": "leave",
                    "source_ref": src,
                    "start": s,
                    "stop": e,
                    "minutes": minutes,
                    "state": state or "planned",
                    "branch_id": branch or False,
                })

            if Av:
                avs = Av.sudo().search([
                    ("staff_id", "=", rec.staff_id.id),
                    ("is_blocking", "=", True),
                    ("availability_type", "in", ("leave", "unavailable")),
                    ("start", "<=", end_dt),
                    ("stop", ">=", start_dt),
                ])
                for av in avs:
                    m = _overlap_minutes(av.start, av.stop, start_dt, end_dt)
                    add_av_line(f"{av._name},{av.id}", av.start, av.stop, m, branch=av.branch_id.id if av.branch_id else False)

            if AvOcc:
                ovs = AvOcc.sudo().search([
                    ("staff_id", "=", rec.staff_id.id),
                    ("is_blocking", "=", True),
                    ("availability_type", "in", ("leave", "unavailable")),
                    ("state", "in", ("planned", "applied")),
                    ("start", "<=", end_dt),
                    ("stop", ">=", start_dt),
                ])
                for ov in ovs:
                    m = _overlap_minutes(ov.start, ov.stop, start_dt, end_dt)
                    add_av_line(f"{ov._name},{ov.id}", ov.start, ov.stop, m, state=ov.state, branch=ov.branch_id.id if ov.branch_id else False)

            if vals_batch:
                Line.create(vals_batch)

