# Utilities
# ============================================================

def _overlap_minutes(a_start, a_stop, b_start, b_stop):
    """Hitung menit overlap dua interval waktu [start, stop)."""
    if not (a_start and a_stop and b_start and b_stop):
        return 0
    start = max(a_start, b_start)
    stop = min(a_stop, b_stop)
    if stop <= start:
        return 0
    return int((stop - start).total_seconds() // 60)


def _to_hours(minutes):
    return round(float(minutes) / 60.0, 2)


