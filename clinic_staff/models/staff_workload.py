class ClinicStaffWorkloadLine(models.Model):
    _name = "clinic.staff.workload.line"
    _description = "Staff Workload Line"
    _order = "start, id"

    workload_id = fields.Many2one(
        "clinic.staff.workload",
        string="Workload",
        required=True,
        index=True,
        ondelete="cascade"
    )

    company_id = fields.Many2one(
        "res.company",
        string="Company",
        related="workload_id.company_id",
        store=True,
        readonly=True
    )

    branch_id = fields.Many2one(
        "clinic.branch",
        string="Branch",
        help="Branch context of the source record."
    )

    source_type = fields.Selection(
        selection=[
            ("roster", "Roster"),
            ("assignment_planned", "Assignment (Planned)"),
            ("assignment_actual", "Assignment (Actual)"),
            ("leave", "Leave/Unavailable"),
        ],
        string="Source Type",
        required=True,
        index=True
    )

    source_ref = fields.Char(
        string="Source",
        help="Technical reference '<model>,<id>' to the source record."
    )

    start = fields.Datetime(
        string="Start",
        required=True,
        index=True
    )

    stop = fields.Datetime(
        string="Stop",
        required=True,
        index=True
    )

    minutes = fields.Integer(
        string="Minutes",
        required=True,
        help="Minutes contributing to the workload from this source record."
    )

    hours = fields.Float(
        string="Hours",
        compute="_compute_hours",
        store=False
    )

    state = fields.Char(
        string="State",
        help="State of the source record at the time of capturing."
    )

    note = fields.Char(
        string="Note",
        help="Optional short note or tag."
    )

    def _compute_hours(self):
        for rec in self:
            rec.hours = _to_hours(rec.minutes)

    # Quick smart actions
    def action_open_source(self):
        """Buka source record (jika model tersedia)."""
        self.ensure_one()
        if not self.source_ref or "," not in self.source_ref:
            return False
        model, rec_id = self.source_ref.split(",", 1)
        try:
            rec_id_int = int(rec_id)
        except Exception:
            return False

        Model = self.env.get(model)
        if not Model:
            return False
        if not Model.browse(rec_id_int).exists():
            return False

        return {
            "name": _("Source Record"),
            "type": "ir.actions.act_window",
            "res_model": model,
            "view_mode": "form",
            "res_id": rec_id_int,
            "target": "current",
        }

